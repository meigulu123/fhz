# ============================ 写出 JSON ============================
def main():
    nodes = [{"id": nid, "lecture": text} for nid, text in LECTURES]
    (KG_DIR / "gen_B.json").write_text(
        json.dumps({"nodes": nodes}, ensure_ascii=False, indent=2), encoding="utf-8")
    (KG_DIR / "gen_q_B.json").write_text(
        json.dumps({"questions": QUESTIONS}, ensure_ascii=False, indent=2), encoding="utf-8")
    print("written: gen_B.json, gen_q_B.json")

    # ---------------- 自检 ----------------
    fails = []

    def check(cond, msg):
        print(("  [OK]   " if cond else "  [FAIL] ") + msg)
        if not cond:
            fails.append(msg)

    # ① JSON 可解析
    lb = json.loads((KG_DIR / "gen_B.json").read_text(encoding="utf-8"))
    lq = json.loads((KG_DIR / "gen_q_B.json").read_text(encoding="utf-8"))
    check(True, "① 两个文件均能被 json.loads 正常解析")

    # ② 12 节点讲义 + [ASK:] ≥2 + 段落字数
    ids = set(NODE_DIFF)
    got_ids = {n["id"] for n in lb["nodes"]}
    check(len(lb["nodes"]) == 12 and got_ids == ids, f"② 12 个节点全部有讲义且 id 正确（{len(lb['nodes'])}）")
    for n in lb["nodes"]:
        nid, lec = n["id"], n["lecture"]
        ask = lec.count("[ASK:]")
        check(ask >= 2, f"② 节点 {nid} [ASK:] 数量 = {ask}")
        if not lec.strip():
            fails.append(f"{nid} 讲义为空")
        # 段落字数：标题与紧随的正文合并为一段；[ASK:] 与“下一步”为独立提问位/过渡句
        blocks = [p for p in lec.split("\n\n") if p.strip()]
        merged = []
        for p in blocks:
            if p.startswith("## "):
                merged.append(p)
            elif p.startswith("[ASK:]") or p.startswith("下一步"):
                merged.append(p)
            else:
                merged[-1] += "\n\n" + p
        for i, p in enumerate(merged):
            if p.startswith("## ") and not (150 <= len(p) <= 350):
                print(f"    [warn] {nid} 第{i+1}段（{p[:14]}…）字数 {len(p)}（要求 150~350）")

    # ③ 36 题
    qs = lq["questions"]
    check(len(qs) == 36, f"③ 题目总数 = {len(qs)}")
    from collections import Counter
    cnt = Counter(q["node_id"] for q in qs)
    bad_nodes = [k for k in cnt if k not in ids]
    check(not bad_nodes, f"③ 全部 node_id 在 12 节点内（引用非法节点：{bad_nodes or '无'}）")
    check(all(v == 3 for v in cnt.values()) and set(cnt) == ids,
          f"③ 每节点 3 题且覆盖全部 12 节点（{dict(cnt)}）")
    ans_dist = Counter()
    v_dist = Counter()
    for q in qs:
        qid = q["id"]
        opts = q.get("options", [])
        letters = [o[:1] for o in opts if o]
        check(q.get("answer") in letters, f"③ {qid} answer 合法")
        check(len(opts) == 4 and all(o[1:2] == "." and o[:1] in "ABCD" for o in opts),
              f"③ {qid} options 为 A~D 四项")
        check(q.get("type") == "single", f"③ {qid} type=single")
        diff_ok = abs(q["difficulty"] - NODE_DIFF[q["node_id"]]) <= 0.2
        check(diff_ok, f"③ {qid} difficulty={q['difficulty']}（节点 {NODE_DIFF[q['node_id']]} ±0.2）")
        for lv in ("L0", "L1", "L2", "L3"):
            check(bool(q.get("hints", {}).get(lv)), f"③ {qid} hints.{lv} 非空")
        ans_dist[q["answer"]] += 1
        v = q.get("variant", {})
        vopts = v.get("options", [])
        vletters = [o[:1] for o in vopts if o]
        check(bool(v.get("stem")) and len(vopts) == 4 and v.get("answer") in vletters
              and bool(v.get("explanation")), f"③ {qid} variant 完整")
        v_dist[v.get("answer", "?")] += 1
    print(f"    主答案分布: {dict(ans_dist)}；变式答案分布: {dict(v_dist)}")

    print()
    if fails:
        print(f"自检未通过：{len(fails)} 项")
        raise SystemExit(1)
    print("自检全部通过。")

if __name__ == "__main__":
    main()
