def _verify():
    problems = []

    # 1) 两个文件能被 json.loads 正常解析
    try:
        lec = json.loads(OUT_LEC.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[FAIL] gen_A.json 解析失败: {e}")
        return 1
    try:
        qs = json.loads(OUT_Q.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[FAIL] gen_q_A.json 解析失败: {e}")
        return 1

    # 2) 讲义：12 节点齐全、每份 [ASK:] >= 2、正文段落 150~350 字
    lec_map = {}
    for item in lec["nodes"]:
        lec_map[item["id"]] = item["lecture"]
    if set(lec_map) != set(NODE_ORDER) or len(lec_map) != 12:
        problems.append(f"讲义节点集合错误: {sorted(lec_map)}")
    for nid in NODE_ORDER:
        text = lec_map.get(nid, "")
        if text.count("[ASK:]") < 2:
            problems.append(f"{nid} 讲义 [ASK:] 数量 < 2")
        paras = []
        for block in text.split("\n\n"):
            block = "\n".join(
                ln for ln in block.split("\n") if not ln.lstrip().startswith("## "))
            block = block.strip()
            if not block or block.startswith("[ASK:]") or block.startswith("**下一步**"):
                continue
            paras.append(block)
        ok_cnt = sum(1 for p in paras if 150 <= len(p) <= 350)
        if len(paras) < 3 or ok_cnt < 3:
            problems.append(f"{nid} 正文段落数/字数不合规: 段落 {len(paras)} 个, "
                            f"150~350 字的 {ok_cnt} 个, 各段长度 {[len(p) for p in paras]}")
        else:
            print(f"  [OK] {nid} 讲义: 段落 {len(paras)} 个（{ok_cnt} 个在 150~350 字）, [ASK:] x{text.count('[ASK:]')}")

    # 3) 题目：36 题、node_id 合法、difficulty 接近节点、hints 四档、answer/variant 合法
    all_qs = qs["questions"]
    if len(all_qs) != 36:
        problems.append(f"题目总数 {len(all_qs)} != 36")
    seen = set()
    for q in all_qs:
        qid, nid = q.get("id"), q.get("node_id")
        if qid in seen:
            problems.append(f"题目 id 重复: {qid}")
        seen.add(qid)
        if nid not in NODE_ORDER:
            problems.append(f"{qid} node_id 非法: {nid}")
            continue
        if q.get("type") != "single":
            problems.append(f"{qid} type 非 single")
        if abs(q.get("difficulty", 0) - NODE_DIFF[nid]) > 0.2 + 1e-9:
            problems.append(f"{qid} difficulty {q['difficulty']} 偏离节点 {NODE_DIFF[nid]} 超过 0.2")
        opts = q.get("options", [])
        letters = [o[:1] for o in opts if o]
        if len(opts) != 4 or letters != ["A", "B", "C", "D"]:
            problems.append(f"{qid} options 格式错误: {opts}")
        if q.get("answer") not in letters:
            problems.append(f"{qid} answer {q.get('answer')} 不在 options 中")
        for lv in ("L0", "L1", "L2", "L3"):
            if not q.get("hints", {}).get(lv):
                problems.append(f"{qid} 缺少提示档 {lv}")
        v = q.get("variant", {})
        vopts = v.get("options", [])
        vletters = [o[:1] for o in vopts if o]
        if not (v.get("stem") and v.get("explanation") and len(vopts) == 4
                and vletters == ["A", "B", "C", "D"]):
            problems.append(f"{qid} 变式题字段不完整")
        if v.get("answer") not in vletters:
            problems.append(f"{qid} 变式题 answer {v.get('answer')} 不在 options 中")
        if v.get("stem") == q.get("stem"):
            problems.append(f"{qid} 变式题与母题题干完全相同")

    if problems:
        print("[FAIL] 发现以下问题：")
        for p in problems:
            print("  -", p)
        return 1
    print(f"[OK] 全部自检通过：12 节点讲义 / {len(all_qs)} 题")
    return 0


def main():
    nodes = [{"id": nid, "lecture": LECTURES[nid]} for nid in NODE_ORDER]
    OUT_LEC.write_text(json.dumps({"nodes": nodes}, ensure_ascii=False, indent=2),
                       encoding="utf-8")
    OUT_Q.write_text(json.dumps({"questions": QUESTIONS}, ensure_ascii=False, indent=2),
                     encoding="utf-8")
    print(f"已写出 {OUT_LEC}")
    print(f"已写出 {OUT_Q}")
    return _verify()


if __name__ == "__main__":
    raise SystemExit(main())
