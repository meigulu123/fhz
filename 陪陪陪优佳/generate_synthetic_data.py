def generate_disease_data():
    """生成NDJSON格式的疾病数据"""
    diseases = []
    disease_id = 10000

    for category, disease_list in DISEASES.items():
        for d in disease_list:
            record = {
                "_id": {"$oid": f"{disease_id:024x}"},
                "name": d["name"],
                "desc": d["desc"],
                "category": d["category"],
                "prevent": d["prevent"],
                "cause": d["cause"],
                "symptom": d["symptom"],
                "yibao_status": d["yibao_status"],
                "get_prob": d["get_prob"],
                "get_way": d["get_way"],
                "acompany": d["acompany"],
                "cure_department": d["cure_department"],
                "cure_way": d["cure_way"],
                "cure_lasttime": d["cure_lasttime"],
                "cured_prob": d["cured_prob"],
                "cost_money": d["cost_money"],
                "check": d["check"],
                "recommand_drug": d["recommand_drug"],
                "drug_detail": d["drug_detail"],
            }
            diseases.append(record)
            disease_id += 1

    return diseases


def generate_qa_data(num_per_category=100):
    """生成QA对话数据"""
    qa_pairs = []

    for category, templates in QA_TEMPLATES.items():
        # 先加入模板QA
        for q, a in templates:
            qa_pairs.append({
                "category": category,
                "query": q,
                "response": a
            })

    return qa_pairs


def generate_extended_qa(diseases, num=200):
    """基于疾病数据扩展生成更多QA"""
    qa_pairs = []
    for d in diseases:
        name = d["name"]
        symptoms = d.get("symptom", [])
        drugs = d.get("recommand_drug", [])
        cause = d.get("cause", "")[:100]
        prevent = d.get("prevent", "")[:100]
        cure_way = d.get("cure_way", [])
        dept = d.get("cure_department", [])

        # 问题变体
        questions = [
            f"{name}有哪些症状？",
            f"{name}怎么治疗？",
            f"{name}的病因是什么？",
            f"如何预防{name}？",
            f"{name}应该看什么科室？",
            f"{name}需要做哪些检查？",
            f"{name}能治好吗？",
            f"{name}常用什么药？",
        ]

        answers = [
            f"{name}的主要症状包括：{'、'.join(symptoms[:8])}。",
            f"{name}的治疗方式包括：{'、'.join(cure_way[:6])}。具体方案需根据病情严重程度在医生指导下制定。",
            f"{name}的病因：{cause}",
            f"预防{name}的措施：{prevent}",
            f"{name}应就诊{'、'.join(dept[:3])}。",
            f"{name}需要做以下检查：{'、'.join(d.get('check', ['常规检查'])[:8])}。",
            f"{name}的预后：{d.get('cured_prob', '需积极治疗')}。",
            f"{name}常用药物：{'、'.join(drugs[:5])}。请在医生指导下使用。",
        ]

        for q, a in zip(questions, answers):
            if q and a:
                qa_pairs.append({"query": q, "response": a})

    return qa_pairs


