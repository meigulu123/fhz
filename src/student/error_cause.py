"""错因判定（共享模块）：错题本归类与脚手架靶向干预共用同一套错因口径

四类错因（确定性启发式，判据来自题库与画像，可解释、可回归）：
- 概念混淆：同一考点反复出错（该题累计答错 ≥ 2 次）
- 基础薄弱：该知识点掌握度 θ < 0.4（前置链条没打牢）
- 粗心/审题：难点题（难度 ≥ 0.7）做错但掌握度 ≥ 0.6
- 理解偏差：其余（会一点但没吃透）

同一口径在上下游两处消费：①错题本归类展示与错因分布统计；
②脚手架 L0 靶向反问——不同错因问不同的问题，而不是所有学生都问同一句。
"""
from __future__ import annotations

CAUSES = ("概念混淆", "基础薄弱", "粗心/审题", "理解偏差")

ADVICE = {
    "概念混淆": "同一考点反复出错，建议回看讲义把这个概念重新梳理一遍",
    "基础薄弱": "该知识点掌握度偏低，先补前置知识再练这类题",
    "粗心/审题": "知识点本身掌握不错，多半是审题或计算失误，练习时放慢读题",
    "理解偏差": "会一点但没吃透，建议看完解析立刻做一道变式题验证",
}

# 脚手架靶向反问（L0）：按错因给出不同的引导方向，都不直接给答案
PROBES = {
    "概念混淆": "这道题考的概念，和哪个概念最容易混？先把两个概念的定义各说一遍，再回来对选项。",
    "基础薄弱": "先别急着做这道题——它用到的前置知识你还记得吗？把那个前置结论说清楚，这道题就有路了。",
    "粗心/审题": "先只看题干：已知条件有哪几条？一条条圈出来，看看有没有被漏掉的条件。",
    "理解偏差": "你的思路看着有道理，但它成立的边界在哪？哪一步是你没验证就跳过去的？",
}


def advice_for(cause: str, node_name: str = "", count: int = 1) -> str:
    """按「错因 + 具体知识点 + 答错次数」生成差异化建议

    同一错因落到不同知识点、不同错题次数上，给的话术必须不同，
    否则错题本的「建议」栏会千人一面，学生看了也不知道下一步做什么。
    """
    where = f"「{node_name}」" if node_name else "这个知识点"
    n = max(int(count or 1), 1)
    if cause == "概念混淆":
        return (f"{where}同一个考点已经错 {n} 次，说明不是完全不会，而是概念边界没分清——"
                "回看讲义把最容易混的两个概念各写一句定义，再回来重做这道题。")
    if cause == "基础薄弱":
        return (f"{where}的掌握度偏低，多半是它的先修知识没打牢："
                "先去学习路径里补上先修节点，再回来练这类题，比硬啃省时间。")
    if cause == "粗心/审题":
        return (f"{where}你其实掌握了，错的更像审题或计算："
                "练这类题时先把已知条件逐条圈出来、写出算式再选，别跳步。")
    return (f"你对{where}算是会一点、但没吃透：看完解析立刻做一道变式题，"
            "把「为什么这样成立」讲给自己听，验证是不是真懂了。")


def error_cause(q, profile=None, count: int = 1, node_name: str = "") -> tuple:
    """错因归类：返回 (错因标签, 学习建议)

    count 为该题累计答错次数（错题本按同题聚合统计；脚手架用连错次数）；
    node_name 供生成针对性建议文案（缺省时用「这个知识点」兜底）。
    """
    nid = q.get("node_id")
    theta = profile.mastery.get(nid, 0.0) if profile else 0.0
    diff = q.get("difficulty", 0.5) or 0.5
    if count >= 2:
        cause = CAUSES[0]
    elif theta < 0.4:
        cause = CAUSES[1]
    elif diff >= 0.7 and theta >= 0.6:
        cause = CAUSES[2]
    else:
        cause = CAUSES[3]
    return cause, advice_for(cause, node_name=node_name, count=count)


def cause_probe(cause: str) -> str:
    """脚手架靶向反问句；未知错因返回通用引导"""
    return PROBES.get(cause, "先想一想：这道题在考哪个知识点？它给出的条件能推出什么？")


def cause_note(cause: str) -> str:
    """给真实大模型的干预指令：说明该生错在哪一类，要求据此引导"""
    if cause in PROBES:
        return (f"该生本题错因判定为「{cause}」。请围绕这个错因引导"
                f"（参考方向：{PROBES[cause]}），逐级缩小范围，不要直接给出答案。")
    return "请按层级逐级引导，不要直接给出答案。"
